-- MAGIC # 04_dim_osm_road_class
-- MAGIC
-- MAGIC Dimensão de classes de via do OpenStreetMap (esquema `fclass` da Geofabrik), com descrição em português, grupo e hierarquia viária. Atualizada por `MERGE`; a chave substituta `COD_DIM_CLASSE_VIA` não muda entre cargas.
-- MAGIC
-- MAGIC Regras:
-- MAGIC
-- MAGIC 1. Chave natural: `COD_CLASSE` (`fclass`). As classes do esquema da Geofabrik estão transcritas abaixo; uma classe nova que apareça na Silver entra com a descrição `Outras` e é apontada pela qualidade.
-- MAGIC 2. `NUM_HIERARQUIA`: 1 (vias expressas) a 9 (trilhas). `FLG_TRAFEGO_MOTORIZADO` separa as vias de veículos das de pedestres e ciclistas.
-- MAGIC 3. Membro desconhecido: `COD_DIM_CLASSE_VIA = -1` (`NÃO INFORMADO`).

-- COMMAND ----------

CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_osm_road_class (
  COD_DIM_CLASSE_VIA      BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica da classe de via (-1 = nao informado)',
  COD_CLASSE              STRING NOT NULL COMMENT 'Classe da via no esquema da Geofabrik (fclass), chave natural',
  DSC_CLASSE              STRING COMMENT 'Descricao da classe em portugues',
  DSC_GRUPO               STRING COMMENT 'Grupo: Vias principais, Acessos, Vias locais, Servico, Nao motorizadas, Trilhas ou Outras',
  NUM_HIERARQUIA          INT    COMMENT 'Hierarquia viaria: 1 (vias expressas) a 9 (trilhas)',
  FLG_TRAFEGO_MOTORIZADO  BOOLEAN COMMENT 'Via de trafego de veiculos',
  DAT_CARGA_DIMENSAO      TIMESTAMP COMMENT 'Data e hora da primeira carga do registro',
  DAT_ULT_ATUALIZACAO     TIMESTAMP COMMENT 'Data e hora da ultima atualizacao do registro',
  CONSTRAINT pk_dim_osm_road_class PRIMARY KEY (COD_DIM_CLASSE_VIA)
)
COMMENT 'Dimensao de classes de via do OpenStreetMap (esquema da Geofabrik). © OpenStreetMap contributors, ODbL 1.0';

-- COMMAND ----------

-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_osm_road_class AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_CLASSE_VIA) AS s
  ON t.COD_DIM_CLASSE_VIA = s.COD_DIM_CLASSE_VIA
WHEN NOT MATCHED THEN INSERT (
  COD_DIM_CLASSE_VIA, COD_CLASSE, DSC_CLASSE, DSC_GRUPO, NUM_HIERARQUIA, FLG_TRAFEGO_MOTORIZADO,
  DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  -1, 'N/I', 'NÃO INFORMADO', 'NÃO INFORMADO', NULL, NULL, current_timestamp(), current_timestamp()
);

-- COMMAND ----------

-- Classes de via da camada roads da Geofabrik (https://download.geofabrik.de/osm-data-in-gis-formats-free.pdf).
CREATE OR REPLACE TEMP VIEW classes_geofabrik AS
SELECT * FROM VALUES
  ('motorway',       'Via expressa',                         'Vias principais', 1, TRUE),
  ('trunk',          'Via arterial de primeira linha',       'Vias principais', 2, TRUE),
  ('primary',        'Via arterial',                         'Vias principais', 3, TRUE),
  ('secondary',      'Via coletora principal',               'Vias principais', 4, TRUE),
  ('tertiary',       'Via coletora',                         'Vias principais', 5, TRUE),
  ('motorway_link',  'Acesso a via expressa',                'Acessos',         1, TRUE),
  ('trunk_link',     'Acesso a via arterial de primeira linha', 'Acessos',      2, TRUE),
  ('primary_link',   'Acesso a via arterial',                'Acessos',         3, TRUE),
  ('secondary_link', 'Acesso a via coletora principal',      'Acessos',         4, TRUE),
  ('tertiary_link',  'Acesso a via coletora',                'Acessos',         5, TRUE),
  ('unclassified',   'Via local não classificada',           'Vias locais',     6, TRUE),
  ('residential',    'Rua residencial',                      'Vias locais',     6, TRUE),
  ('living_street',  'Rua de convivência',                   'Vias locais',     6, TRUE),
  ('busway',         'Corredor exclusivo de ônibus',         'Vias locais',     6, TRUE),
  ('service',        'Via de serviço (acesso a lotes, estacionamentos)', 'Serviço', 7, TRUE),
  ('pedestrian',     'Rua de pedestres',                     'Não motorizadas', 8, FALSE),
  ('footway',        'Calçada ou caminho de pedestres',      'Não motorizadas', 8, FALSE),
  ('steps',          'Escadaria',                            'Não motorizadas', 8, FALSE),
  ('cycleway',       'Ciclovia',                             'Não motorizadas', 8, FALSE),
  ('path',           'Caminho de uso misto',                 'Não motorizadas', 8, FALSE),
  ('bridleway',      'Caminho para cavalos',                 'Não motorizadas', 8, FALSE),
  ('track',          'Estrada de terra (rural ou florestal)', 'Trilhas',        9, TRUE),
  ('track_grade1',   'Estrada de terra, pavimento firme',    'Trilhas',         9, TRUE),
  ('track_grade2',   'Estrada de terra, cascalho',           'Trilhas',         9, TRUE),
  ('track_grade3',   'Estrada de terra, mista',              'Trilhas',         9, TRUE),
  ('track_grade4',   'Estrada de terra, solo compactado',    'Trilhas',         9, TRUE),
  ('track_grade5',   'Estrada de terra, solo solto',         'Trilhas',         9, TRUE),
  ('unknown',        'Via de tipo desconhecido',             'Outras',          NULL, NULL)
AS c(cd_classe, dc_classe, dc_grupo, nr_hierarquia, fl_trafego_motorizado);

-- Classes do esquema mais as que aparecerem na Silver sem estar nele.
CREATE OR REPLACE TEMP VIEW stg_dim_osm_road_class AS
SELECT cd_classe AS COD_CLASSE, dc_classe AS DSC_CLASSE, dc_grupo AS DSC_GRUPO,
       nr_hierarquia AS NUM_HIERARQUIA, fl_trafego_motorizado AS FLG_TRAFEGO_MOTORIZADO
FROM classes_geofabrik
UNION ALL
SELECT DISTINCT s.cd_classe, s.cd_classe, 'Outras', CAST(NULL AS INT), CAST(NULL AS BOOLEAN)
FROM fiap_analytics.silver.osm_roads s
  LEFT ANTI JOIN classes_geofabrik c ON s.cd_classe = c.cd_classe
WHERE s.cd_classe IS NOT NULL;

-- COMMAND ----------

MERGE INTO fiap_analytics.gold.dim_osm_road_class AS t
USING stg_dim_osm_road_class AS s
  ON t.COD_CLASSE = s.COD_CLASSE
WHEN MATCHED AND (
     NOT (t.DSC_CLASSE             <=> s.DSC_CLASSE)
  OR NOT (t.DSC_GRUPO              <=> s.DSC_GRUPO)
  OR NOT (t.NUM_HIERARQUIA         <=> s.NUM_HIERARQUIA)
  OR NOT (t.FLG_TRAFEGO_MOTORIZADO <=> s.FLG_TRAFEGO_MOTORIZADO)
) THEN UPDATE SET
  DSC_CLASSE = s.DSC_CLASSE, DSC_GRUPO = s.DSC_GRUPO, NUM_HIERARQUIA = s.NUM_HIERARQUIA,
  FLG_TRAFEGO_MOTORIZADO = s.FLG_TRAFEGO_MOTORIZADO, DAT_ULT_ATUALIZACAO = current_timestamp()
WHEN NOT MATCHED THEN INSERT (
  COD_CLASSE, DSC_CLASSE, DSC_GRUPO, NUM_HIERARQUIA, FLG_TRAFEGO_MOTORIZADO, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  s.COD_CLASSE, s.DSC_CLASSE, s.DSC_GRUPO, s.NUM_HIERARQUIA, s.FLG_TRAFEGO_MOTORIZADO, current_timestamp(), current_timestamp()
);

-- COMMAND ----------

SELECT * FROM fiap_analytics.gold.dim_osm_road_class ORDER BY NUM_HIERARQUIA NULLS LAST, DSC_GRUPO, COD_CLASSE
