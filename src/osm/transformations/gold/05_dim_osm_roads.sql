-- MAGIC %md
-- MAGIC # 05_dim_osm_roads
-- MAGIC
-- MAGIC Dimensão espacial das vias do OpenStreetMap no recorte do município de São Paulo: uma linha por via, com classe, nome, sentido, velocidade máxima, ponte, túnel, comprimento, centroide, envelope e geometria. É a referência para o cruzamento com as ocorrências do GeoSampa (vias próximas a um alagamento) e com as áreas de suscetibilidade do SGB.
-- MAGIC
-- MAGIC Regras:
-- MAGIC
-- MAGIC 1. Chave natural: `NUM_OSM_ID` (identificador da *way* no OSM). A chave substituta `COD_DIM_VIA` não muda entre cargas.
-- MAGIC 2. `MERGE` a partir da Silver: atualiza o que mudou no extrato novo, insere as vias novas e remove as que saíram do OSM. O membro `-1` nunca é removido.
-- MAGIC 3. Classe fora da dimensão vai para o membro `-1` da `dim_osm_road_class`.
-- MAGIC 4. `GEO_WKB` em EPSG 4674 (longitude e latitude). O envelope serve para pré-filtrar cruzamentos espaciais em SQL.
-- MAGIC
-- MAGIC Dados © colaboradores do OpenStreetMap, ODbL 1.0: todo produto feito a partir desta tabela precisa trazer a atribuição.

-- COMMAND ----------

CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_osm_roads (
  COD_DIM_VIA              BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica da via (-1 = nao informado)',
  NUM_OSM_ID               BIGINT NOT NULL COMMENT 'Identificador da way no OpenStreetMap (chave natural)',
  COD_DIM_CLASSE_VIA       BIGINT NOT NULL COMMENT 'Chave da dimensao de classes de via (-1 = nao informado)',
  NOM_VIA                  STRING COMMENT 'Nome da via',
  COD_REFERENCIA           STRING COMMENT 'Codigo de referencia da via (por exemplo, SP-150)',
  DSC_SENTIDO              STRING COMMENT 'Mao dupla ou mao unica (sentido do desenho ou contrario)',
  FLG_MAO_UNICA            BOOLEAN COMMENT 'Via de mao unica',
  NUM_VELOCIDADE_MAX_KMH   INT    COMMENT 'Velocidade maxima em km/h (nulo se nao informada)',
  NUM_NIVEL                INT    COMMENT 'Nivel relativo da via (layer do OSM; negativo = abaixo do solo)',
  FLG_PONTE                BOOLEAN COMMENT 'Trecho em ponte ou viaduto',
  FLG_TUNEL                BOOLEAN COMMENT 'Trecho em tunel',
  NUM_COMPRIMENTO_KM       DOUBLE COMMENT 'Comprimento da via em km, calculado em SIRGAS 2000 / UTM 23S',
  NUM_CENTROIDE_LATITUDE   DOUBLE COMMENT 'Latitude do centroide em graus',
  NUM_CENTROIDE_LONGITUDE  DOUBLE COMMENT 'Longitude do centroide em graus',
  NUM_LAT_MIN              DOUBLE COMMENT 'Envelope: menor latitude',
  NUM_LAT_MAX              DOUBLE COMMENT 'Envelope: maior latitude',
  NUM_LON_MIN              DOUBLE COMMENT 'Envelope: menor longitude',
  NUM_LON_MAX              DOUBLE COMMENT 'Envelope: maior longitude',
  GEO_WKB                  BINARY COMMENT 'Geometria em WKB, EPSG 4674 (longitude e latitude)',
  DSC_VERSAO_FONTE         STRING COMMENT 'Data do extrato da Geofabrik',
  DAT_INGESTAO_BRONZE      TIMESTAMP COMMENT 'Data e hora da ingestao na Bronze',
  DAT_CARGA_DIMENSAO       TIMESTAMP COMMENT 'Data e hora da primeira carga do registro',
  DAT_ULT_ATUALIZACAO      TIMESTAMP COMMENT 'Data e hora da ultima atualizacao do registro',
  CONSTRAINT pk_dim_osm_roads PRIMARY KEY (COD_DIM_VIA),
  CONSTRAINT fk_dim_osm_roads_classe FOREIGN KEY (COD_DIM_CLASSE_VIA)
    REFERENCES fiap_analytics.gold.dim_osm_road_class (COD_DIM_CLASSE_VIA)
)
CLUSTER BY (COD_DIM_CLASSE_VIA, NUM_CENTROIDE_LATITUDE, NUM_CENTROIDE_LONGITUDE)
COMMENT 'Dimensao espacial das vias do OpenStreetMap no recorte do municipio de Sao Paulo. © OpenStreetMap contributors, ODbL 1.0';

-- COMMAND ----------

-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_osm_roads AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_VIA) AS s
  ON t.COD_DIM_VIA = s.COD_DIM_VIA
WHEN NOT MATCHED THEN INSERT (
  COD_DIM_VIA, NUM_OSM_ID, COD_DIM_CLASSE_VIA, NOM_VIA, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  -1, -1, -1, 'NÃO INFORMADO', current_timestamp(), current_timestamp()
);

-- COMMAND ----------

CREATE OR REPLACE TEMP VIEW stg_dim_osm_roads AS
SELECT
  s.nr_osm_id                          AS NUM_OSM_ID,
  COALESCE(c.COD_DIM_CLASSE_VIA, -1)   AS COD_DIM_CLASSE_VIA,
  s.nm_via                             AS NOM_VIA,
  s.cd_referencia                      AS COD_REFERENCIA,
  s.dc_sentido                         AS DSC_SENTIDO,
  s.fl_mao_unica                       AS FLG_MAO_UNICA,
  s.nr_velocidade_max_kmh              AS NUM_VELOCIDADE_MAX_KMH,
  s.nr_nivel                           AS NUM_NIVEL,
  s.fl_ponte                           AS FLG_PONTE,
  s.fl_tunel                           AS FLG_TUNEL,
  s.nr_comprimento_km                  AS NUM_COMPRIMENTO_KM,
  s.nr_centroide_latitude              AS NUM_CENTROIDE_LATITUDE,
  s.nr_centroide_longitude             AS NUM_CENTROIDE_LONGITUDE,
  s.nr_lat_min                         AS NUM_LAT_MIN,
  s.nr_lat_max                         AS NUM_LAT_MAX,
  s.nr_lon_min                         AS NUM_LON_MIN,
  s.nr_lon_max                         AS NUM_LON_MAX,
  s.geom_wkb                           AS GEO_WKB,
  s._source_version                    AS DSC_VERSAO_FONTE,
  s._ingested_at                       AS DAT_INGESTAO_BRONZE
FROM fiap_analytics.silver.osm_roads s
  LEFT JOIN fiap_analytics.gold.dim_osm_road_class c ON s.cd_classe = c.COD_CLASSE;

-- COMMAND ----------

MERGE INTO fiap_analytics.gold.dim_osm_roads AS t
USING stg_dim_osm_roads AS s
  ON t.NUM_OSM_ID = s.NUM_OSM_ID
WHEN MATCHED AND (
     NOT (t.COD_DIM_CLASSE_VIA     <=> s.COD_DIM_CLASSE_VIA)
  OR NOT (t.NOM_VIA                <=> s.NOM_VIA)
  OR NOT (t.COD_REFERENCIA         <=> s.COD_REFERENCIA)
  OR NOT (t.DSC_SENTIDO            <=> s.DSC_SENTIDO)
  OR NOT (t.NUM_VELOCIDADE_MAX_KMH <=> s.NUM_VELOCIDADE_MAX_KMH)
  OR NOT (t.NUM_NIVEL              <=> s.NUM_NIVEL)
  OR NOT (t.FLG_PONTE              <=> s.FLG_PONTE)
  OR NOT (t.FLG_TUNEL              <=> s.FLG_TUNEL)
  OR NOT (t.GEO_WKB                <=> s.GEO_WKB)
) THEN UPDATE SET
  COD_DIM_CLASSE_VIA = s.COD_DIM_CLASSE_VIA, NOM_VIA = s.NOM_VIA, COD_REFERENCIA = s.COD_REFERENCIA,
  DSC_SENTIDO = s.DSC_SENTIDO, FLG_MAO_UNICA = s.FLG_MAO_UNICA, NUM_VELOCIDADE_MAX_KMH = s.NUM_VELOCIDADE_MAX_KMH,
  NUM_NIVEL = s.NUM_NIVEL, FLG_PONTE = s.FLG_PONTE, FLG_TUNEL = s.FLG_TUNEL, NUM_COMPRIMENTO_KM = s.NUM_COMPRIMENTO_KM,
  NUM_CENTROIDE_LATITUDE = s.NUM_CENTROIDE_LATITUDE, NUM_CENTROIDE_LONGITUDE = s.NUM_CENTROIDE_LONGITUDE,
  NUM_LAT_MIN = s.NUM_LAT_MIN, NUM_LAT_MAX = s.NUM_LAT_MAX, NUM_LON_MIN = s.NUM_LON_MIN, NUM_LON_MAX = s.NUM_LON_MAX,
  GEO_WKB = s.GEO_WKB, DSC_VERSAO_FONTE = s.DSC_VERSAO_FONTE, DAT_INGESTAO_BRONZE = s.DAT_INGESTAO_BRONZE,
  DAT_ULT_ATUALIZACAO = current_timestamp()
WHEN NOT MATCHED THEN INSERT (
  NUM_OSM_ID, COD_DIM_CLASSE_VIA, NOM_VIA, COD_REFERENCIA, DSC_SENTIDO, FLG_MAO_UNICA, NUM_VELOCIDADE_MAX_KMH,
  NUM_NIVEL, FLG_PONTE, FLG_TUNEL, NUM_COMPRIMENTO_KM, NUM_CENTROIDE_LATITUDE, NUM_CENTROIDE_LONGITUDE,
  NUM_LAT_MIN, NUM_LAT_MAX, NUM_LON_MIN, NUM_LON_MAX, GEO_WKB, DSC_VERSAO_FONTE, DAT_INGESTAO_BRONZE,
  DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  s.NUM_OSM_ID, s.COD_DIM_CLASSE_VIA, s.NOM_VIA, s.COD_REFERENCIA, s.DSC_SENTIDO, s.FLG_MAO_UNICA, s.NUM_VELOCIDADE_MAX_KMH,
  s.NUM_NIVEL, s.FLG_PONTE, s.FLG_TUNEL, s.NUM_COMPRIMENTO_KM, s.NUM_CENTROIDE_LATITUDE, s.NUM_CENTROIDE_LONGITUDE,
  s.NUM_LAT_MIN, s.NUM_LAT_MAX, s.NUM_LON_MIN, s.NUM_LON_MAX, s.GEO_WKB, s.DSC_VERSAO_FONTE, s.DAT_INGESTAO_BRONZE,
  current_timestamp(), current_timestamp()
)
WHEN NOT MATCHED BY SOURCE AND t.COD_DIM_VIA <> -1 THEN DELETE;

-- COMMAND ----------

SELECT c.DSC_GRUPO, c.COD_CLASSE, COUNT(*) AS VIAS, ROUND(SUM(v.NUM_COMPRIMENTO_KM), 1) AS EXTENSAO_KM
FROM fiap_analytics.gold.dim_osm_roads v
  JOIN fiap_analytics.gold.dim_osm_road_class c ON v.COD_DIM_CLASSE_VIA = c.COD_DIM_CLASSE_VIA
WHERE v.COD_DIM_VIA <> -1
GROUP BY ALL
ORDER BY EXTENSAO_KM DESC
