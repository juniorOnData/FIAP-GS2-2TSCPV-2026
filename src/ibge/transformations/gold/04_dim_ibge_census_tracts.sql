-- MAGIC # 04_dim_ibge_census_tracts
-- MAGIC
-- MAGIC Dimensão espacial dos setores censitários do Censo 2022 no município de São Paulo: uma linha por setor, com situação, tipo, distrito, subdistrito, bairro, favela, área, centroide, envelope e geometria. Atualizada por `MERGE` a partir da Silver; a chave substituta `COD_DIM_SETOR` não muda entre cargas.
-- MAGIC
-- MAGIC Regras:
-- MAGIC
-- MAGIC 1. Chave natural: `COD_SETOR` (geocódigo de 15 dígitos do IBGE).
-- MAGIC 2. Setores que saem da Silver (uma versão corrigida da malha) saem da dimensão. O membro `-1` (`NÃO INFORMADO`) nunca é removido.
-- MAGIC 3. `GEO_WKB` em SIRGAS 2000 geográfico (EPSG 4674). O envelope serve para pré-filtrar cruzamentos espaciais (ocorrência do GeoSampa dentro do setor, setor dentro de uma área de suscetibilidade do SGB).

-- COMMAND ----------

CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_ibge_census_tracts (
  COD_DIM_SETOR            BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica do setor (-1 = nao informado)',
  COD_SETOR                STRING NOT NULL COMMENT 'Geocodigo do setor censitario do IBGE (15 digitos, chave natural)',
  DSC_SITUACAO             STRING COMMENT 'Situacao do setor: Urbana ou Rural (nulo em massas de agua)',
  COD_SITUACAO_DETALHADA   STRING COMMENT 'Situacao detalhada (1 a 9)',
  DSC_SITUACAO_DETALHADA   STRING COMMENT 'Descricao da situacao detalhada',
  COD_TIPO_SETOR           STRING COMMENT 'Tipo do setor (0 a 9)',
  DSC_TIPO_SETOR           STRING COMMENT 'Descricao do tipo do setor',
  FLG_FAVELA               BOOLEAN COMMENT 'Setor do tipo Favela e Comunidade Urbana',
  COD_DISTRITO             STRING COMMENT 'Codigo do distrito (IBGE)',
  NOM_DISTRITO             STRING COMMENT 'Nome do distrito',
  COD_SUBDISTRITO          STRING COMMENT 'Codigo do subdistrito',
  NOM_SUBDISTRITO          STRING COMMENT 'Nome do subdistrito',
  COD_BAIRRO               STRING COMMENT 'Codigo do bairro (nulo se o IBGE nao delimita bairros no municipio)',
  NOM_BAIRRO               STRING COMMENT 'Nome do bairro',
  COD_FAVELA               STRING COMMENT 'Codigo da favela ou comunidade urbana',
  NOM_FAVELA               STRING COMMENT 'Nome da favela ou comunidade urbana',
  NUM_AREA_KM2             DOUBLE COMMENT 'Area do setor em km2 publicada pelo IBGE',
  NUM_CENTROIDE_LATITUDE   DOUBLE COMMENT 'Latitude do centroide em graus (SIRGAS 2000)',
  NUM_CENTROIDE_LONGITUDE  DOUBLE COMMENT 'Longitude do centroide em graus (SIRGAS 2000)',
  NUM_LAT_MIN              DOUBLE COMMENT 'Envelope: menor latitude',
  NUM_LAT_MAX              DOUBLE COMMENT 'Envelope: maior latitude',
  NUM_LON_MIN              DOUBLE COMMENT 'Envelope: menor longitude',
  NUM_LON_MAX              DOUBLE COMMENT 'Envelope: maior longitude',
  GEO_WKB                  BINARY COMMENT 'Geometria em WKB, SIRGAS 2000 geografico (EPSG 4674, longitude e latitude)',
  DSC_VERSAO_FONTE         STRING COMMENT 'Data da coleta da malha no IBGE (versao carregada)',
  DAT_INGESTAO_BRONZE      TIMESTAMP COMMENT 'Data e hora da ingestao na Bronze',
  DAT_CARGA_DIMENSAO       TIMESTAMP COMMENT 'Data e hora da primeira carga do registro',
  DAT_ULT_ATUALIZACAO      TIMESTAMP COMMENT 'Data e hora da ultima atualizacao do registro',
  CONSTRAINT pk_dim_ibge_census_tracts PRIMARY KEY (COD_DIM_SETOR)
)
CLUSTER BY (COD_DISTRITO)
COMMENT 'Dimensao espacial dos setores censitarios do Censo 2022 (IBGE) no municipio de Sao Paulo';

-- COMMAND ----------

-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_ibge_census_tracts AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_SETOR) AS s
  ON t.COD_DIM_SETOR = s.COD_DIM_SETOR
WHEN NOT MATCHED THEN INSERT (
  COD_DIM_SETOR, COD_SETOR, DSC_SITUACAO, DSC_SITUACAO_DETALHADA, DSC_TIPO_SETOR, FLG_FAVELA,
  NOM_DISTRITO, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  -1, 'N/I', 'NÃO INFORMADO', 'NÃO INFORMADO', 'NÃO INFORMADO', FALSE, 'NÃO INFORMADO', current_timestamp(), current_timestamp()
);

-- COMMAND ----------

MERGE INTO fiap_analytics.gold.dim_ibge_census_tracts AS t
USING (
  SELECT
    cd_setor AS COD_SETOR, dc_situacao AS DSC_SITUACAO, cd_situacao_detalhada AS COD_SITUACAO_DETALHADA,
    dc_situacao_detalhada AS DSC_SITUACAO_DETALHADA, cd_tipo_setor AS COD_TIPO_SETOR, dc_tipo_setor AS DSC_TIPO_SETOR,
    fl_favela AS FLG_FAVELA, cd_distrito AS COD_DISTRITO, nm_distrito AS NOM_DISTRITO,
    cd_subdistrito AS COD_SUBDISTRITO, nm_subdistrito AS NOM_SUBDISTRITO, cd_bairro AS COD_BAIRRO, nm_bairro AS NOM_BAIRRO,
    cd_favela AS COD_FAVELA, nm_favela AS NOM_FAVELA, nr_area_ibge_km2 AS NUM_AREA_KM2,
    nr_centroide_latitude AS NUM_CENTROIDE_LATITUDE, nr_centroide_longitude AS NUM_CENTROIDE_LONGITUDE,
    nr_lat_min AS NUM_LAT_MIN, nr_lat_max AS NUM_LAT_MAX, nr_lon_min AS NUM_LON_MIN, nr_lon_max AS NUM_LON_MAX,
    geom_wkb AS GEO_WKB, _source_version AS DSC_VERSAO_FONTE, _ingested_at AS DAT_INGESTAO_BRONZE
  FROM fiap_analytics.silver.ibge_census_tracts
) AS s
  ON t.COD_SETOR = s.COD_SETOR
WHEN MATCHED AND (
     NOT (t.DSC_SITUACAO           <=> s.DSC_SITUACAO)
  OR NOT (t.COD_SITUACAO_DETALHADA <=> s.COD_SITUACAO_DETALHADA)
  OR NOT (t.COD_TIPO_SETOR         <=> s.COD_TIPO_SETOR)
  OR NOT (t.COD_DISTRITO           <=> s.COD_DISTRITO)
  OR NOT (t.NOM_DISTRITO           <=> s.NOM_DISTRITO)
  OR NOT (t.COD_SUBDISTRITO        <=> s.COD_SUBDISTRITO)
  OR NOT (t.COD_BAIRRO             <=> s.COD_BAIRRO)
  OR NOT (t.NOM_BAIRRO             <=> s.NOM_BAIRRO)
  OR NOT (t.COD_FAVELA             <=> s.COD_FAVELA)
  OR NOT (t.NOM_FAVELA             <=> s.NOM_FAVELA)
  OR NOT (t.NUM_AREA_KM2           <=> s.NUM_AREA_KM2)
  OR NOT (t.GEO_WKB                <=> s.GEO_WKB)
  OR NOT (t.DSC_VERSAO_FONTE       <=> s.DSC_VERSAO_FONTE)
  OR NOT (t.DAT_INGESTAO_BRONZE    <=> s.DAT_INGESTAO_BRONZE)
) THEN UPDATE SET
  DSC_SITUACAO = s.DSC_SITUACAO, COD_SITUACAO_DETALHADA = s.COD_SITUACAO_DETALHADA,
  DSC_SITUACAO_DETALHADA = s.DSC_SITUACAO_DETALHADA, COD_TIPO_SETOR = s.COD_TIPO_SETOR, DSC_TIPO_SETOR = s.DSC_TIPO_SETOR,
  FLG_FAVELA = s.FLG_FAVELA, COD_DISTRITO = s.COD_DISTRITO, NOM_DISTRITO = s.NOM_DISTRITO,
  COD_SUBDISTRITO = s.COD_SUBDISTRITO, NOM_SUBDISTRITO = s.NOM_SUBDISTRITO, COD_BAIRRO = s.COD_BAIRRO, NOM_BAIRRO = s.NOM_BAIRRO,
  COD_FAVELA = s.COD_FAVELA, NOM_FAVELA = s.NOM_FAVELA, NUM_AREA_KM2 = s.NUM_AREA_KM2,
  NUM_CENTROIDE_LATITUDE = s.NUM_CENTROIDE_LATITUDE, NUM_CENTROIDE_LONGITUDE = s.NUM_CENTROIDE_LONGITUDE,
  NUM_LAT_MIN = s.NUM_LAT_MIN, NUM_LAT_MAX = s.NUM_LAT_MAX, NUM_LON_MIN = s.NUM_LON_MIN, NUM_LON_MAX = s.NUM_LON_MAX,
  GEO_WKB = s.GEO_WKB, DSC_VERSAO_FONTE = s.DSC_VERSAO_FONTE, DAT_INGESTAO_BRONZE = s.DAT_INGESTAO_BRONZE,
  DAT_ULT_ATUALIZACAO = current_timestamp()
WHEN NOT MATCHED THEN INSERT (
  COD_SETOR, DSC_SITUACAO, COD_SITUACAO_DETALHADA, DSC_SITUACAO_DETALHADA, COD_TIPO_SETOR, DSC_TIPO_SETOR, FLG_FAVELA,
  COD_DISTRITO, NOM_DISTRITO, COD_SUBDISTRITO, NOM_SUBDISTRITO, COD_BAIRRO, NOM_BAIRRO, COD_FAVELA, NOM_FAVELA,
  NUM_AREA_KM2, NUM_CENTROIDE_LATITUDE, NUM_CENTROIDE_LONGITUDE, NUM_LAT_MIN, NUM_LAT_MAX, NUM_LON_MIN, NUM_LON_MAX,
  GEO_WKB, DSC_VERSAO_FONTE, DAT_INGESTAO_BRONZE, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  s.COD_SETOR, s.DSC_SITUACAO, s.COD_SITUACAO_DETALHADA, s.DSC_SITUACAO_DETALHADA, s.COD_TIPO_SETOR, s.DSC_TIPO_SETOR, s.FLG_FAVELA,
  s.COD_DISTRITO, s.NOM_DISTRITO, s.COD_SUBDISTRITO, s.NOM_SUBDISTRITO, s.COD_BAIRRO, s.NOM_BAIRRO, s.COD_FAVELA, s.NOM_FAVELA,
  s.NUM_AREA_KM2, s.NUM_CENTROIDE_LATITUDE, s.NUM_CENTROIDE_LONGITUDE, s.NUM_LAT_MIN, s.NUM_LAT_MAX, s.NUM_LON_MIN, s.NUM_LON_MAX,
  s.GEO_WKB, s.DSC_VERSAO_FONTE, s.DAT_INGESTAO_BRONZE, current_timestamp(), current_timestamp()
)
WHEN NOT MATCHED BY SOURCE AND t.COD_DIM_SETOR <> -1 THEN DELETE;

-- COMMAND ----------

SELECT NOM_DISTRITO, COUNT(*) AS SETORES, COUNT_IF(FLG_FAVELA) AS SETORES_FAVELA, ROUND(SUM(NUM_AREA_KM2), 2) AS AREA_KM2
FROM fiap_analytics.gold.dim_ibge_census_tracts
WHERE COD_DIM_SETOR <> -1
GROUP BY ALL
ORDER BY 1
