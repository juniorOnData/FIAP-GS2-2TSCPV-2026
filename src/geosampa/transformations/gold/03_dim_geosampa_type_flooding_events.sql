-- [SQL] E01 Criação da tabela
CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_geosampa_type_flooding_events (
  COD_DIM_OCORRENCIA  BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica do tipo de ocorrência (-1 = nao informado)',
  DSC_TIPO_OCORRENCIA STRING NOT NULL COMMENT 'Descricao do tipo de ocorrência',
  DAT_CARGA_DIMENSAO  TIMESTAMP COMMENT 'Data e hora em que o tipo entrou na dimensao',
  CONSTRAINT pk_dim_geosampa_type_flooding_events PRIMARY KEY (COD_DIM_OCORRENCIA)
)
COMMENT 'Dimensao de tipos de ocorrência (alagamento, deslizamento, inundacao e outros)';

-- COMMAND ----------

-- [SQL] E02 Membro não informado
-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_geosampa_type_flooding_events AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_OCORRENCIA) AS s
  ON t.COD_DIM_OCORRENCIA = s.COD_DIM_OCORRENCIA
WHEN NOT MATCHED THEN INSERT (COD_DIM_OCORRENCIA, DSC_TIPO_OCORRENCIA, DAT_CARGA_DIMENSAO)
VALUES (-1, 'Não informado', current_timestamp());

-- COMMAND ----------

-- [SQL] E03 Tipos novos
INSERT INTO fiap_analytics.gold.dim_geosampa_type_flooding_events (DSC_TIPO_OCORRENCIA, DAT_CARGA_DIMENSAO)
SELECT
  s.dc_tipo_ocorrencia,
  current_timestamp() AS dt_carga
FROM (
  SELECT DISTINCT dc_tipo_ocorrencia
  FROM fiap_analytics.silver.geosampa_flooding_events
  WHERE dc_tipo_ocorrencia IS NOT NULL
) s
LEFT ANTI JOIN fiap_analytics.gold.dim_geosampa_type_flooding_events d
  ON s.dc_tipo_ocorrencia = d.DSC_TIPO_OCORRENCIA;

-- COMMAND ----------

-- [SQL] E04 Consulta do resultado
SELECT * FROM fiap_analytics.gold.dim_geosampa_type_flooding_events ORDER BY COD_DIM_OCORRENCIA
