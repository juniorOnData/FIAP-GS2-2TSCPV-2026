-- MAGIC %md
-- MAGIC # 04_dim_cemaden_stations
-- MAGIC
-- MAGIC Dimensão de estações do CEMADEN, atualizada por `MERGE` (SCD tipo 1) a partir da Silver. A chave substituta `COD_DIM_ESTACAO` não muda entre cargas.
-- MAGIC
-- MAGIC Membro desconhecido: a linha `COD_DIM_ESTACAO = -1` (`NÃO INFORMADO`) recebe as leituras de estações que não estão no cadastro, para a fato nunca ficar com chave nula.

-- COMMAND ----------

CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_cemaden_stations (
  COD_DIM_ESTACAO          BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica da estacao (-1 = nao informado)',
  COD_ESTACAO              STRING NOT NULL COMMENT 'Codigo da estacao no CEMADEN (chave natural)',
  COD_ID_ESTACAO           STRING    COMMENT 'Identificador interno da estacao na PED',
  NOM_ESTACAO              STRING    COMMENT 'Nome da estacao',
  NOM_CIDADE               STRING    COMMENT 'Municipio',
  SIG_UF                   STRING    COMMENT 'Unidade da federacao',
  NUM_LATITUDE             DOUBLE    COMMENT 'Latitude em graus',
  NUM_LONGITUDE            DOUBLE    COMMENT 'Longitude em graus',
  NUM_ALTITUDE             DOUBLE    COMMENT 'Altitude',
  DSC_TIPO_ESTACAO         STRING    COMMENT 'Tipo de estacao',
  SIG_REDE                 STRING    COMMENT 'Sigla da rede',
  DAT_INSTALACAO           DATE      COMMENT 'Data de instalacao',
  DAT_INICIO_INATIVO       TIMESTAMP COMMENT 'Inicio da inatividade (UTC); nulo se ativa',
  FLG_ATIVA                BOOLEAN   COMMENT 'Estacao ativa',
  FLG_NO_CADASTRO_ATUAL    BOOLEAN   COMMENT 'Estacao presente no cadastro mais recente',
  DAT_CARGA_DIMENSAO       TIMESTAMP COMMENT 'Data e hora da primeira carga do registro',
  DAT_ULT_ATUALIZACAO      TIMESTAMP COMMENT 'Data e hora da ultima atualizacao do registro',
  CONSTRAINT pk_dim_cemaden_stations PRIMARY KEY (COD_DIM_ESTACAO)
)
COMMENT 'Dimensao de estacoes pluviometricas do CEMADEN no municipio de Sao Paulo';

-- COMMAND ----------

-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_cemaden_stations AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_ESTACAO) AS s
  ON t.COD_DIM_ESTACAO = s.COD_DIM_ESTACAO
WHEN NOT MATCHED THEN INSERT (
  COD_DIM_ESTACAO, COD_ESTACAO, NOM_ESTACAO, FLG_ATIVA, FLG_NO_CADASTRO_ATUAL, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  -1, 'N/I', 'NÃO INFORMADO', FALSE, FALSE, current_timestamp(), current_timestamp()
);

-- COMMAND ----------

MERGE INTO fiap_analytics.gold.dim_cemaden_stations AS t
USING fiap_analytics.silver.cemaden_stations AS s
  ON t.COD_ESTACAO = s.cod_estacao
WHEN MATCHED AND (
     NOT (t.COD_ID_ESTACAO        <=> s.cod_id_estacao)
  OR NOT (t.NOM_ESTACAO           <=> s.nm_estacao)
  OR NOT (t.NOM_CIDADE            <=> s.nm_cidade)
  OR NOT (t.SIG_UF                <=> s.sg_uf)
  OR NOT (t.NUM_LATITUDE          <=> s.nr_latitude)
  OR NOT (t.NUM_LONGITUDE         <=> s.nr_longitude)
  OR NOT (t.NUM_ALTITUDE          <=> s.nr_altitude)
  OR NOT (t.DSC_TIPO_ESTACAO      <=> s.dc_tipo_estacao)
  OR NOT (t.SIG_REDE              <=> s.sg_rede)
  OR NOT (t.DAT_INSTALACAO        <=> s.dt_instalacao)
  OR NOT (t.DAT_INICIO_INATIVO    <=> s.dt_hr_inicio_inativo)
  OR NOT (t.FLG_ATIVA             <=> s.fl_ativa)
  OR NOT (t.FLG_NO_CADASTRO_ATUAL <=> s.fl_no_cadastro_atual)
) THEN UPDATE SET
  COD_ID_ESTACAO        = s.cod_id_estacao,
  NOM_ESTACAO           = s.nm_estacao,
  NOM_CIDADE            = s.nm_cidade,
  SIG_UF                = s.sg_uf,
  NUM_LATITUDE          = s.nr_latitude,
  NUM_LONGITUDE         = s.nr_longitude,
  NUM_ALTITUDE          = s.nr_altitude,
  DSC_TIPO_ESTACAO      = s.dc_tipo_estacao,
  SIG_REDE              = s.sg_rede,
  DAT_INSTALACAO        = s.dt_instalacao,
  DAT_INICIO_INATIVO    = s.dt_hr_inicio_inativo,
  FLG_ATIVA             = s.fl_ativa,
  FLG_NO_CADASTRO_ATUAL = s.fl_no_cadastro_atual,
  DAT_ULT_ATUALIZACAO   = current_timestamp()
WHEN NOT MATCHED THEN INSERT (
  COD_ESTACAO, COD_ID_ESTACAO, NOM_ESTACAO, NOM_CIDADE, SIG_UF, NUM_LATITUDE, NUM_LONGITUDE, NUM_ALTITUDE,
  DSC_TIPO_ESTACAO, SIG_REDE, DAT_INSTALACAO, DAT_INICIO_INATIVO, FLG_ATIVA, FLG_NO_CADASTRO_ATUAL,
  DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  s.cod_estacao, s.cod_id_estacao, s.nm_estacao, s.nm_cidade, s.sg_uf, s.nr_latitude, s.nr_longitude, s.nr_altitude,
  s.dc_tipo_estacao, s.sg_rede, s.dt_instalacao, s.dt_hr_inicio_inativo, s.fl_ativa, s.fl_no_cadastro_atual,
  current_timestamp(), current_timestamp()
);

-- COMMAND ----------

SELECT * FROM fiap_analytics.gold.dim_cemaden_stations ORDER BY COD_DIM_ESTACAO
