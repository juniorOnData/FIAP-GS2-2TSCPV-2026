-- MAGIC
-- MAGIC Dimensão de classes da carta de suscetibilidade do SGB: uma linha por camada e classe (por exemplo, inundação Alta, movimento de massa Média, relevo Colinas). Atualizada por `MERGE` a partir da Silver. A chave substituta `COD_DIM_CLASSE` não muda entre cargas.
-- MAGIC
-- MAGIC Regras:
-- MAGIC
-- MAGIC 1. Chave natural: `COD_CAMADA` + `DSC_CLASSE`. `NUM_GRAU_SUSCETIBILIDADE` vale 3 (Alta), 2 (Média) ou 1 (Baixa), e fica nulo no relevo e nas camadas sem graduação.
-- MAGIC 2. As características predominantes, a declividade e a área de cada classe vêm dos quadros-síntese da carta (arquivos `QuadroSintese_*.docx` do pacote), transcritos abaixo.
-- MAGIC 3. Membro desconhecido: a linha `COD_DIM_CLASSE = -1` (`NÃO INFORMADO`).

-- COMMAND ----------

CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_sgb_susceptibility_class (
  COD_DIM_CLASSE               BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica da classe (-1 = nao informado)',
  COD_CAMADA                   STRING NOT NULL COMMENT 'Camada da carta (inundacao, bacia_inundacao, enxurrada, movimento_massa, corrida_massa, relevo)',
  DSC_CAMADA                   STRING COMMENT 'Descricao da camada',
  DSC_CLASSE                   STRING NOT NULL COMMENT 'Classe: Alta, Media, Baixa, Sem graduacao ou o padrao de relevo',
  NUM_GRAU_SUSCETIBILIDADE     INT    COMMENT 'Grau de suscetibilidade: 3 = Alta, 2 = Media, 1 = Baixa (nulo sem graduacao)',
  DSC_DECLIVIDADE              STRING COMMENT 'Declividade predominante da classe, segundo o quadro-sintese da carta',
  DSC_CARACTERISTICAS          STRING COMMENT 'Caracteristicas predominantes da classe, segundo o quadro-sintese da carta',
  NUM_AREA_QUADRO_SINTESE_KM2  DOUBLE COMMENT 'Area da classe informada no quadro-sintese da carta, em km2',
  DAT_CARGA_DIMENSAO           TIMESTAMP COMMENT 'Data e hora da primeira carga do registro',
  DAT_ULT_ATUALIZACAO          TIMESTAMP COMMENT 'Data e hora da ultima atualizacao do registro',
  CONSTRAINT pk_dim_sgb_susceptibility_class PRIMARY KEY (COD_DIM_CLASSE)
)
COMMENT 'Dimensao de classes da carta de suscetibilidade a movimentos de massa e inundacoes do municipio de Sao Paulo (SGB/CPRM e IPT, 2015)';

-- COMMAND ----------

-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_sgb_susceptibility_class AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_CLASSE) AS s
  ON t.COD_DIM_CLASSE = s.COD_DIM_CLASSE
WHEN NOT MATCHED THEN INSERT (
  COD_DIM_CLASSE, COD_CAMADA, DSC_CAMADA, DSC_CLASSE, NUM_GRAU_SUSCETIBILIDADE, DSC_DECLIVIDADE,
  DSC_CARACTERISTICAS, NUM_AREA_QUADRO_SINTESE_KM2, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  -1, 'N/I', 'NÃO INFORMADO', 'NÃO INFORMADO', NULL, NULL, NULL, NULL, current_timestamp(), current_timestamp()
);

