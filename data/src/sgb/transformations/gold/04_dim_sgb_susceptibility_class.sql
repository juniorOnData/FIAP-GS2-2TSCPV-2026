CREATE OR REPLACE TEMP VIEW stg_dim_sgb_susceptibility_class AS
SELECT
  s.cd_camada AS COD_CAMADA,
  MAX(s.dc_camada) AS DSC_CAMADA,
  s.dc_classe AS DSC_CLASSE,
  MAX(s.nr_grau_suscetibilidade) AS NUM_GRAU_SUSCETIBILIDADE,
  MAX(q.dc_declividade) AS DSC_DECLIVIDADE,
  MAX(q.dc_caracteristicas) AS DSC_CARACTERISTICAS,
  MAX(q.nr_area_km2) AS NUM_AREA_QUADRO_SINTESE_KM2
FROM fiap_analytics.silver.sgb_susceptibility_areas s
  LEFT JOIN quadro_sintese q ON s.cd_camada = q.cd_camada AND s.dc_classe = q.dc_classe
WHERE s.dc_classe IS NOT NULL
GROUP BY s.cd_camada, s.dc_classe;

-- COMMAND ----------

MERGE INTO fiap_analytics.gold.dim_sgb_susceptibility_class AS t
USING stg_dim_sgb_susceptibility_class AS s
  ON t.COD_CAMADA = s.COD_CAMADA AND t.DSC_CLASSE = s.DSC_CLASSE
WHEN MATCHED AND (
     NOT (t.DSC_CAMADA                  <=> s.DSC_CAMADA)
  OR NOT (t.NUM_GRAU_SUSCETIBILIDADE    <=> s.NUM_GRAU_SUSCETIBILIDADE)
  OR NOT (t.DSC_DECLIVIDADE             <=> s.DSC_DECLIVIDADE)
  OR NOT (t.DSC_CARACTERISTICAS         <=> s.DSC_CARACTERISTICAS)
  OR NOT (t.NUM_AREA_QUADRO_SINTESE_KM2 <=> s.NUM_AREA_QUADRO_SINTESE_KM2)
) THEN UPDATE SET
  DSC_CAMADA                  = s.DSC_CAMADA,
  NUM_GRAU_SUSCETIBILIDADE    = s.NUM_GRAU_SUSCETIBILIDADE,
  DSC_DECLIVIDADE             = s.DSC_DECLIVIDADE,
  DSC_CARACTERISTICAS         = s.DSC_CARACTERISTICAS,
  NUM_AREA_QUADRO_SINTESE_KM2 = s.NUM_AREA_QUADRO_SINTESE_KM2,
  DAT_ULT_ATUALIZACAO         = current_timestamp()
WHEN NOT MATCHED THEN INSERT (
  COD_CAMADA, DSC_CAMADA, DSC_CLASSE, NUM_GRAU_SUSCETIBILIDADE, DSC_DECLIVIDADE, DSC_CARACTERISTICAS,
  NUM_AREA_QUADRO_SINTESE_KM2, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  s.COD_CAMADA, s.DSC_CAMADA, s.DSC_CLASSE, s.NUM_GRAU_SUSCETIBILIDADE, s.DSC_DECLIVIDADE, s.DSC_CARACTERISTICAS,
  s.NUM_AREA_QUADRO_SINTESE_KM2, current_timestamp(), current_timestamp()
);

