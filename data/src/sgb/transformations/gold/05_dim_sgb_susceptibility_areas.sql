-- MAGIC # 05_dim_sgb_susceptibility_areas
-- MAGIC
-- MAGIC Dimensão espacial das áreas da carta de suscetibilidade do SGB: uma linha por polígono de cada camada, com a classe, a área, o centroide, o envelope e a geometria. É a referência para o cruzamento com as ocorrências do GeoSampa e com os setores do IBGE (ponto ou setor dentro de uma área de suscetibilidade).
-- MAGIC
-- MAGIC Regras:
-- MAGIC
-- MAGIC 1. Chave natural: `COD_CAMADA` + `NUM_ID_FEICAO` (posição da feição no shapefile da versão carregada). A chave substituta `COD_DIM_AREA_SUSCETIBILIDADE` não muda entre cargas da mesma versão.
-- MAGIC 2. `MERGE` a partir da Silver: atualiza o que mudou, insere o novo e remove as feições que saíram da Silver (uma versão nova da carta pode ter outras feições). O membro `-1` nunca é removido.
-- MAGIC 3. Classe não encontrada vai para o membro `-1` da `dim_sgb_susceptibility_class`.
-- MAGIC 4. `GEO_WKB` em SIRGAS 2000 geográfico (EPSG 4674, longitude e latitude). O envelope (`NUM_LAT_MIN`... `NUM_LON_MAX`) serve para pré-filtrar cruzamentos espaciais em SQL.
-- MAGIC 5. Polígonos podem se sobrepor dentro de uma camada (as bacias contribuintes, por exemplo). No cruzamento, um ponto pode cair em mais de uma área: use o maior grau de suscetibilidade.

-- COMMAND ----------

CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_sgb_susceptibility_areas (
  COD_DIM_AREA_SUSCETIBILIDADE  BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica da area (-1 = nao informado)',
  COD_CAMADA              STRING NOT NULL COMMENT 'Camada da carta (inundacao, bacia_inundacao, enxurrada, movimento_massa, corrida_massa, relevo)',
  NUM_ID_FEICAO           INT    NOT NULL COMMENT 'Posicao da feicao no shapefile (com COD_CAMADA, chave natural)',
  COD_DIM_CLASSE          BIGINT NOT NULL COMMENT 'Chave da dimensao de classes (-1 = nao informado)',
  NUM_GRAU_SUSCETIBILIDADE INT   COMMENT 'Grau de suscetibilidade: 3 = Alta, 2 = Media, 1 = Baixa (nulo sem graduacao)',
  NUM_AREA_KM2            DOUBLE COMMENT 'Area do poligono em km2, calculada em SIRGAS 2000 / UTM 23S',
  NUM_CENTROIDE_LATITUDE  DOUBLE COMMENT 'Latitude do centroide em graus (SIRGAS 2000)',
  NUM_CENTROIDE_LONGITUDE DOUBLE COMMENT 'Longitude do centroide em graus (SIRGAS 2000)',
  NUM_LAT_MIN             DOUBLE COMMENT 'Envelope: menor latitude',
  NUM_LAT_MAX             DOUBLE COMMENT 'Envelope: maior latitude',
  NUM_LON_MIN             DOUBLE COMMENT 'Envelope: menor longitude',
  NUM_LON_MAX             DOUBLE COMMENT 'Envelope: maior longitude',
  GEO_WKB                 BINARY COMMENT 'Geometria em WKB, SIRGAS 2000 geografico (EPSG 4674, longitude e latitude)',
  DSC_VERSAO_FONTE        STRING COMMENT 'Data da coleta da carta no RIGEO (versao carregada)',
  DAT_INGESTAO_BRONZE     TIMESTAMP COMMENT 'Data e hora da ingestao na Bronze',
  DAT_CARGA_DIMENSAO      TIMESTAMP COMMENT 'Data e hora da primeira carga do registro',
  DAT_ULT_ATUALIZACAO     TIMESTAMP COMMENT 'Data e hora da ultima atualizacao do registro',
  CONSTRAINT pk_dim_sgb_susceptibility_areas PRIMARY KEY (COD_DIM_AREA_SUSCETIBILIDADE),
  CONSTRAINT fk_dim_sgb_areas_classe FOREIGN KEY (COD_DIM_CLASSE)
    REFERENCES fiap_analytics.gold.dim_sgb_susceptibility_class (COD_DIM_CLASSE)
)
CLUSTER BY (COD_CAMADA, COD_DIM_CLASSE)
COMMENT 'Dimensao espacial das areas da carta de suscetibilidade do SGB/CPRM e IPT (2015), municipio de Sao Paulo, uma linha por poligono';

-- COMMAND ----------

-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_sgb_susceptibility_areas AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_AREA_SUSCETIBILIDADE) AS s
  ON t.COD_DIM_AREA_SUSCETIBILIDADE = s.COD_DIM_AREA_SUSCETIBILIDADE
WHEN NOT MATCHED THEN INSERT (
  COD_DIM_AREA_SUSCETIBILIDADE, COD_CAMADA, NUM_ID_FEICAO, COD_DIM_CLASSE, NUM_GRAU_SUSCETIBILIDADE,
  NUM_AREA_KM2, NUM_CENTROIDE_LATITUDE, NUM_CENTROIDE_LONGITUDE, NUM_LAT_MIN, NUM_LAT_MAX, NUM_LON_MIN, NUM_LON_MAX,
  GEO_WKB, DSC_VERSAO_FONTE, DAT_INGESTAO_BRONZE, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  -1, 'N/I', -1, -1, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, NULL, current_timestamp(), current_timestamp()
);

-- COMMAND ----------

CREATE OR REPLACE TEMP VIEW stg_dim_sgb_susceptibility_areas AS
SELECT
  s.cd_camada                        AS COD_CAMADA,
  s.nr_id_feicao                     AS NUM_ID_FEICAO,
  COALESCE(c.COD_DIM_CLASSE, -1)     AS COD_DIM_CLASSE,
  s.nr_grau_suscetibilidade          AS NUM_GRAU_SUSCETIBILIDADE,
  s.nr_area_km2                      AS NUM_AREA_KM2,
  s.nr_centroide_latitude            AS NUM_CENTROIDE_LATITUDE,
  s.nr_centroide_longitude           AS NUM_CENTROIDE_LONGITUDE,
  s.nr_lat_min                       AS NUM_LAT_MIN,
  s.nr_lat_max                       AS NUM_LAT_MAX,
  s.nr_lon_min                       AS NUM_LON_MIN,
  s.nr_lon_max                       AS NUM_LON_MAX,
  s.geom_wkb                         AS GEO_WKB,
  s._source_version                  AS DSC_VERSAO_FONTE,
  s._ingested_at                     AS DAT_INGESTAO_BRONZE
FROM fiap_analytics.silver.sgb_susceptibility_areas s
  LEFT JOIN fiap_analytics.gold.dim_sgb_susceptibility_class c
    ON s.cd_camada = c.COD_CAMADA AND s.dc_classe = c.DSC_CLASSE;

-- COMMAND ----------

MERGE INTO fiap_analytics.gold.dim_sgb_susceptibility_areas AS t
USING stg_dim_sgb_susceptibility_areas AS s
  ON t.COD_CAMADA = s.COD_CAMADA AND t.NUM_ID_FEICAO = s.NUM_ID_FEICAO
WHEN MATCHED AND (
     NOT (t.COD_DIM_CLASSE           <=> s.COD_DIM_CLASSE)
  OR NOT (t.NUM_GRAU_SUSCETIBILIDADE <=> s.NUM_GRAU_SUSCETIBILIDADE)
  OR NOT (t.NUM_AREA_KM2             <=> s.NUM_AREA_KM2)
  OR NOT (t.GEO_WKB                  <=> s.GEO_WKB)
  OR NOT (t.DSC_VERSAO_FONTE         <=> s.DSC_VERSAO_FONTE)
  OR NOT (t.DAT_INGESTAO_BRONZE      <=> s.DAT_INGESTAO_BRONZE)
) THEN UPDATE SET
  COD_DIM_CLASSE           = s.COD_DIM_CLASSE,
  NUM_GRAU_SUSCETIBILIDADE = s.NUM_GRAU_SUSCETIBILIDADE,
  NUM_AREA_KM2             = s.NUM_AREA_KM2,
  NUM_CENTROIDE_LATITUDE   = s.NUM_CENTROIDE_LATITUDE,
  NUM_CENTROIDE_LONGITUDE  = s.NUM_CENTROIDE_LONGITUDE,
  NUM_LAT_MIN              = s.NUM_LAT_MIN,
  NUM_LAT_MAX              = s.NUM_LAT_MAX,
  NUM_LON_MIN              = s.NUM_LON_MIN,
  NUM_LON_MAX              = s.NUM_LON_MAX,
  GEO_WKB                  = s.GEO_WKB,
  DSC_VERSAO_FONTE         = s.DSC_VERSAO_FONTE,
  DAT_INGESTAO_BRONZE      = s.DAT_INGESTAO_BRONZE,
  DAT_ULT_ATUALIZACAO      = current_timestamp()
WHEN NOT MATCHED THEN INSERT (
  COD_CAMADA, NUM_ID_FEICAO, COD_DIM_CLASSE, NUM_GRAU_SUSCETIBILIDADE, NUM_AREA_KM2,
  NUM_CENTROIDE_LATITUDE, NUM_CENTROIDE_LONGITUDE, NUM_LAT_MIN, NUM_LAT_MAX, NUM_LON_MIN, NUM_LON_MAX,
  GEO_WKB, DSC_VERSAO_FONTE, DAT_INGESTAO_BRONZE, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  s.COD_CAMADA, s.NUM_ID_FEICAO, s.COD_DIM_CLASSE, s.NUM_GRAU_SUSCETIBILIDADE, s.NUM_AREA_KM2,
  s.NUM_CENTROIDE_LATITUDE, s.NUM_CENTROIDE_LONGITUDE, s.NUM_LAT_MIN, s.NUM_LAT_MAX, s.NUM_LON_MIN, s.NUM_LON_MAX,
  s.GEO_WKB, s.DSC_VERSAO_FONTE, s.DAT_INGESTAO_BRONZE, current_timestamp(), current_timestamp()
)
WHEN NOT MATCHED BY SOURCE AND t.COD_DIM_AREA_SUSCETIBILIDADE <> -1 THEN DELETE;

-- COMMAND ----------

SELECT c.COD_CAMADA, c.DSC_CLASSE, COUNT(*) AS AREAS, ROUND(SUM(a.NUM_AREA_KM2), 2) AS AREA_KM2
FROM fiap_analytics.gold.dim_sgb_susceptibility_areas a
  JOIN fiap_analytics.gold.dim_sgb_susceptibility_class c ON a.COD_DIM_CLASSE = c.COD_DIM_CLASSE
GROUP BY ALL
ORDER BY 1, 2
