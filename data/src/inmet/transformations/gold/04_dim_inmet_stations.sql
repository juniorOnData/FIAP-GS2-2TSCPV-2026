-- MAGIC
-- MAGIC Dimensão de estações automáticas do INMET no município de São Paulo, atualizada por `MERGE` a partir da Silver (SCD tipo 1). A chave substituta `COD_DIM_ESTACAO` não muda entre cargas.
-- MAGIC
-- MAGIC Membro desconhecido: a linha `COD_DIM_ESTACAO = -1` (`NÃO INFORMADO`) recebe as medições de estações fora do cadastro, para a fato nunca ficar com chave nula.

-- COMMAND ----------

CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_inmet_stations (
  COD_DIM_ESTACAO      BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica da estacao (-1 = nao informado)',
  COD_ESTACAO          STRING NOT NULL COMMENT 'Codigo da estacao no INMET (por exemplo, A701), chave natural',
  NOM_ESTACAO          STRING COMMENT 'Nome da estacao',
  SIG_UF               STRING COMMENT 'Unidade da federacao',
  NUM_LATITUDE         DOUBLE COMMENT 'Latitude da estacao em graus',
  NUM_LONGITUDE        DOUBLE COMMENT 'Longitude da estacao em graus',
  NUM_ALTITUDE_M       DOUBLE COMMENT 'Altitude da estacao em metros',
  DAT_FUNDACAO         DATE   COMMENT 'Data de fundacao da estacao',
  NUM_ANOS_COM_DADOS   BIGINT COMMENT 'Anos carregados com dados da estacao',
  NUM_ULTIMO_ANO       INT    COMMENT 'Ultimo ano com dados da estacao',
  DAT_CARGA_DIMENSAO   TIMESTAMP COMMENT 'Data e hora da primeira carga do registro',
  DAT_ULT_ATUALIZACAO  TIMESTAMP COMMENT 'Data e hora da ultima atualizacao do registro',
  CONSTRAINT pk_dim_inmet_stations PRIMARY KEY (COD_DIM_ESTACAO)
)
COMMENT 'Dimensao de estacoes automaticas do INMET no municipio de Sao Paulo';

-- COMMAND ----------

-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_inmet_stations AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_ESTACAO) AS s
  ON t.COD_DIM_ESTACAO = s.COD_DIM_ESTACAO
WHEN NOT MATCHED THEN INSERT (COD_DIM_ESTACAO, COD_ESTACAO, NOM_ESTACAO, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO)
VALUES (-1, 'N/I', 'NÃO INFORMADO', current_timestamp(), current_timestamp());

-- COMMAND ----------

MERGE INTO fiap_analytics.gold.dim_inmet_stations AS t
USING fiap_analytics.silver.inmet_stations AS s
  ON t.COD_ESTACAO = s.cod_estacao
WHEN MATCHED AND (
     NOT (t.NOM_ESTACAO        <=> s.nm_estacao)
  OR NOT (t.SIG_UF             <=> s.sg_uf)
  OR NOT (t.NUM_LATITUDE       <=> s.nr_latitude)
  OR NOT (t.NUM_LONGITUDE      <=> s.nr_longitude)
  OR NOT (t.NUM_ALTITUDE_M     <=> s.nr_altitude_m)
  OR NOT (t.DAT_FUNDACAO       <=> s.dt_fundacao)
  OR NOT (t.NUM_ANOS_COM_DADOS <=> s.nr_anos_com_dados)
  OR NOT (t.NUM_ULTIMO_ANO     <=> s.nr_ultimo_ano)
) THEN UPDATE SET
  NOM_ESTACAO = s.nm_estacao, SIG_UF = s.sg_uf, NUM_LATITUDE = s.nr_latitude, NUM_LONGITUDE = s.nr_longitude,
  NUM_ALTITUDE_M = s.nr_altitude_m, DAT_FUNDACAO = s.dt_fundacao, NUM_ANOS_COM_DADOS = s.nr_anos_com_dados,
  NUM_ULTIMO_ANO = s.nr_ultimo_ano, DAT_ULT_ATUALIZACAO = current_timestamp()
WHEN NOT MATCHED THEN INSERT (
  COD_ESTACAO, NOM_ESTACAO, SIG_UF, NUM_LATITUDE, NUM_LONGITUDE, NUM_ALTITUDE_M, DAT_FUNDACAO,
  NUM_ANOS_COM_DADOS, NUM_ULTIMO_ANO, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  s.cod_estacao, s.nm_estacao, s.sg_uf, s.nr_latitude, s.nr_longitude, s.nr_altitude_m, s.dt_fundacao,
  s.nr_anos_com_dados, s.nr_ultimo_ano, current_timestamp(), current_timestamp()
);

-- COMMAND ----------

SELECT * FROM fiap_analytics.gold.dim_inmet_stations ORDER BY COD_DIM_ESTACAO
