-- MAGIC %md
-- MAGIC # 06_dim_sibh_sensors
-- MAGIC
-- MAGIC Dimensão de sensores do SIBH (chuva e nível), atualizada por `MERGE` (SCD tipo 1) a partir da Silver. A chave substituta `COD_DIM_SENSOR` não muda entre cargas.
-- MAGIC
-- MAGIC Membro desconhecido: a linha `COD_DIM_SENSOR = -1` (`NÃO INFORMADO`) recebe as medições de sensores que não estão no cadastro, para as fatos nunca ficarem com chave nula.

-- COMMAND ----------

CREATE TABLE IF NOT EXISTS fiap_analytics.gold.dim_sibh_sensors (
  COD_DIM_SENSOR           BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY (START WITH 1 INCREMENT BY 1)
    COMMENT 'Chave substituta numerica do sensor (-1 = nao informado)',
  COD_SENSOR               STRING NOT NULL COMMENT 'Identificador do sensor no SIBH (chave natural)',
  COD_ESTACAO              STRING    COMMENT 'Local fisico da estacao (sensores de chuva e nivel do mesmo local compartilham o codigo)',
  COD_PREFIXO              STRING    COMMENT 'Prefixo da estacao',
  NOM_ESTACAO              STRING    COMMENT 'Nome da estacao',
  DSC_GRANDEZA             STRING    COMMENT 'Chuva ou Nivel',
  DSC_TIPO_SENSOR          STRING    COMMENT 'Tipo do sensor conforme o SIBH',
  NOM_INSTITUICAO          STRING    COMMENT 'Instituicao responsavel (SP Aguas, SAISP, SABESP...)',
  NUM_LATITUDE             DOUBLE    COMMENT 'Latitude em graus',
  NUM_LONGITUDE            DOUBLE    COMMENT 'Longitude em graus',
  NOM_MUNICIPIO            STRING    COMMENT 'Municipio',
  SIG_UGRHI                STRING    COMMENT 'Sigla da UGRHI',
  NOM_UGRHI                STRING    COMMENT 'Nome da UGRHI',
  FLG_EM_OPERACAO          BOOLEAN   COMMENT 'Sensor em operacao',
  FLG_NO_CADASTRO_ATUAL    BOOLEAN   COMMENT 'Sensor presente no cadastro mais recente',
  DAT_ULTIMA_MEDICAO       TIMESTAMP COMMENT 'Ultima medicao informada no cadastro (UTC)',
  DAT_CARGA_DIMENSAO       TIMESTAMP COMMENT 'Data e hora da primeira carga do registro',
  DAT_ULT_ATUALIZACAO      TIMESTAMP COMMENT 'Data e hora da ultima atualizacao do registro',
  CONSTRAINT pk_dim_sibh_sensors PRIMARY KEY (COD_DIM_SENSOR)
)
COMMENT 'Dimensao de sensores de chuva e nivel do SIBH (SP Aguas) no municipio de Sao Paulo';

-- COMMAND ----------

-- Membro desconhecido (-1), inserido uma vez.
MERGE INTO fiap_analytics.gold.dim_sibh_sensors AS t
USING (SELECT CAST(-1 AS BIGINT) AS COD_DIM_SENSOR) AS s
  ON t.COD_DIM_SENSOR = s.COD_DIM_SENSOR
WHEN NOT MATCHED THEN INSERT (
  COD_DIM_SENSOR, COD_SENSOR, NOM_ESTACAO, DSC_GRANDEZA, FLG_EM_OPERACAO, FLG_NO_CADASTRO_ATUAL,
  DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  -1, 'N/I', 'NÃO INFORMADO', 'Não informado', FALSE, FALSE, current_timestamp(), current_timestamp()
);

-- COMMAND ----------

MERGE INTO fiap_analytics.gold.dim_sibh_sensors AS t
USING fiap_analytics.silver.sibh_stations AS s
  ON t.COD_SENSOR = s.cod_sensor
WHEN MATCHED AND (
     NOT (t.COD_ESTACAO           <=> s.cod_estacao)
  OR NOT (t.COD_PREFIXO           <=> s.cod_prefixo)
  OR NOT (t.NOM_ESTACAO           <=> s.nm_estacao)
  OR NOT (t.DSC_GRANDEZA          <=> s.dc_grandeza)
  OR NOT (t.DSC_TIPO_SENSOR       <=> s.dc_tipo_sensor)
  OR NOT (t.NOM_INSTITUICAO       <=> s.nm_instituicao)
  OR NOT (t.NUM_LATITUDE          <=> s.nr_latitude)
  OR NOT (t.NUM_LONGITUDE         <=> s.nr_longitude)
  OR NOT (t.NOM_MUNICIPIO         <=> s.nm_municipio)
  OR NOT (t.SIG_UGRHI             <=> s.sg_ugrhi)
  OR NOT (t.NOM_UGRHI             <=> s.nm_ugrhi)
  OR NOT (t.FLG_EM_OPERACAO       <=> s.fl_em_operacao)
  OR NOT (t.FLG_NO_CADASTRO_ATUAL <=> s.fl_no_cadastro_atual)
  OR NOT (t.DAT_ULTIMA_MEDICAO    <=> s.dt_hr_ultima_medicao)
) THEN UPDATE SET
  COD_ESTACAO           = s.cod_estacao,
  COD_PREFIXO           = s.cod_prefixo,
  NOM_ESTACAO           = s.nm_estacao,
  DSC_GRANDEZA          = s.dc_grandeza,
  DSC_TIPO_SENSOR       = s.dc_tipo_sensor,
  NOM_INSTITUICAO       = s.nm_instituicao,
  NUM_LATITUDE          = s.nr_latitude,
  NUM_LONGITUDE         = s.nr_longitude,
  NOM_MUNICIPIO         = s.nm_municipio,
  SIG_UGRHI             = s.sg_ugrhi,
  NOM_UGRHI             = s.nm_ugrhi,
  FLG_EM_OPERACAO       = s.fl_em_operacao,
  FLG_NO_CADASTRO_ATUAL = s.fl_no_cadastro_atual,
  DAT_ULTIMA_MEDICAO    = s.dt_hr_ultima_medicao,
  DAT_ULT_ATUALIZACAO   = current_timestamp()
WHEN NOT MATCHED THEN INSERT (
  COD_SENSOR, COD_ESTACAO, COD_PREFIXO, NOM_ESTACAO, DSC_GRANDEZA, DSC_TIPO_SENSOR, NOM_INSTITUICAO,
  NUM_LATITUDE, NUM_LONGITUDE, NOM_MUNICIPIO, SIG_UGRHI, NOM_UGRHI, FLG_EM_OPERACAO, FLG_NO_CADASTRO_ATUAL,
  DAT_ULTIMA_MEDICAO, DAT_CARGA_DIMENSAO, DAT_ULT_ATUALIZACAO
) VALUES (
  s.cod_sensor, s.cod_estacao, s.cod_prefixo, s.nm_estacao, s.dc_grandeza, s.dc_tipo_sensor, s.nm_instituicao,
  s.nr_latitude, s.nr_longitude, s.nm_municipio, s.sg_ugrhi, s.nm_ugrhi, s.fl_em_operacao, s.fl_no_cadastro_atual,
  s.dt_hr_ultima_medicao, current_timestamp(), current_timestamp()
);

-- COMMAND ----------

SELECT * FROM fiap_analytics.gold.dim_sibh_sensors ORDER BY COD_DIM_SENSOR
